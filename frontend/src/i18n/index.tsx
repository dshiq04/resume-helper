const messages: Record<Locale, Record<MessageKey, string>> = {
  "zh-CN": zhCNMessages,
  "zh-TW": zhTWMessages,
  en,
  ja: jaMessages,
  ko: koMessages,
};

export type Locale = "zh-CN" | "zh-TW" | "en" | "ja" | "ko";

export const localeOptions: Array<{
  value: Locale;
  label: string;
  short: string;
}> = [
  { value: "zh-CN", label: "简体中文", short: "简" },
  { value: "zh-TW", label: "繁體中文", short: "繁" },
  { value: "en", label: "English", short: "EN" },
  { value: "ja", label: "日本語", short: "日" },
  { value: "ko", label: "한국어", short: "한" },
];

function resolveAntdLocale<T extends object>(locale: T): T {
  // Vite/Rolldown can hand back the CommonJS module wrapper instead of its
  // default export. Unwrap it so ConfigProvider always receives locale data.
  const module = locale as T & { default?: T };
  return (module.default ?? locale) as T;
}

const antdLocales = {
  "zh-CN": resolveAntdLocale(zhCN),
  "zh-TW": resolveAntdLocale(zhTW),
  en: resolveAntdLocale(enUS),
  ja: resolveAntdLocale(jaJP),
  ko: resolveAntdLocale(koKR),
} as const;

const LOCALE_KEY = "resumetrail.locale";

function detectLocale(): Locale {
  const saved = localStorage.getItem(LOCALE_KEY);
  if (saved && isLocale(saved)) {
    return saved;
  }
  const languages = navigator.languages?.length
    ? navigator.languages
    : [navigator.language];
  for (const language of languages) {
    const normalized = language.toLowerCase();
    if (normalized.startsWith("zh")) {
      return normalized.includes("tw") ||
        normalized.includes("hk") ||
        normalized.includes("mo")
        ? "zh-TW"
        : "zh-CN";
    }
    if (normalized.startsWith("ja")) return "ja";
    if (normalized.startsWith("ko")) return "ko";
    if (normalized.startsWith("en")) return "en";
  }
  return "zh-CN";
}

function isLocale(value: string): value is Locale {
  return value === "zh-CN" || value === "zh-TW" || value === "en" || value === "ja" || value === "ko";
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, params?: Record<string, string | number>) => string;
  formatDate: (value: string | Date) => string;
  antdLocale: (typeof antdLocales)[Locale];
  localeLabel: string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => detectLocale());

  useEffect(() => {
    localStorage.setItem(LOCALE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
  }, []);

  const t = useCallback(
    (key: MessageKey, params?: Record<string, string | number>) => {
      const template = messages[locale][key] ?? messages.en[key] ?? key;
      if (!params) return template;
      return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
        String(params[name] ?? `{{${name}}}`),
      );
    },
    [locale],
  );

  const formatDate = useCallback(
    (value: string | Date) => {
      const date = value instanceof Date ? value : new Date(value);
      if (Number.isNaN(date.getTime())) return "—";
      return new Intl.DateTimeFormat(locale, {
        month: "short",
        day: "numeric",
        hour: "2-digit",
        minute: "2-digit",
      }).format(date);
    },
    [locale],
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t,
      formatDate,
      antdLocale: antdLocales[locale],
      localeLabel:
        localeOptions.find((option) => option.value === locale)?.label ?? "English",
    }),
    [locale, setLocale, t, formatDate],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return context;
}
